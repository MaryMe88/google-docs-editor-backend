"""Защитный слой постобработки ответа LLM (fail-closed).

Назначение
----------
В финальный пользовательский текст иногда протекают служебные
плейсхолдеры-заглушки, которые модель генерирует вместо реальных
значений, например ``[PERSON_NAME]``, ``[ADDRESS]``, ``[[EMAIL_1]]``.

В проекте нет слоя обратимого обезличивания (reversible redaction) и,
следовательно, нет ``token_map``, из которого можно было бы восстановить
исходные значения. Поэтому «восстановить» плейсхолдер технически не из
чего. Единственная корректная стратегия — **не показывать** пользователю
текст с такими токенами: сначала повторить запрос к LLM с усиленной
инструкцией, а при неудаче — вернуть управляемую ошибку вместо утечки
служебных маркеров в UI (поведение fail-closed).

Модуль намеренно узкий и не тянет внешних зависимостей: только stdlib.
"""

from __future__ import annotations

import re
from typing import List, Pattern

__all__ = [
    "PLACEHOLDER_GUARD_INSTRUCTION",
    "find_placeholder_leaks",
    "has_placeholder_leak",
    "harden_prompt_against_placeholders",
]


# ---------------------------------------------------------------------------
# Детектор служебных плейсхолдеров
# ---------------------------------------------------------------------------
#
# Мы сознательно ловим ТОЛЬКО узкий шаблон служебных токенов, чтобы свести
# к минимуму ложные срабатывания (требование ТЗ, п. «Уменьшить ложные
# срабатывания»):
#
#   * латиница в ВЕРХНЕМ регистре, цифры и подчёркивания;
#   * длиной не менее двух символов внутри скобок;
#   * в одинарных ``[...]`` или двойных ``[[...]]`` квадратных скобках;
#   * опционально с числовым суффиксом (``PERSON_1``, ``EMAIL_001``).
#
# Такой шаблон НЕ задевает:
#   * русский текст в скобках — «[примечание]», «[см. выше]»;
#   * легальные блоки-заголовки режима text_and_report вида
#     «[Исходный ИП: X.X]» (в них есть строчные буквы/кириллица/двоеточие);
#   * markdown-ссылки «[текст](url)» (текст обычно не в ВЕРХНЕМ регистре).
#
# Список ниже собран по наблюдаемым и типовым для LLM-пайплайнов токенам.
_KNOWN_PLACEHOLDER_STEMS: tuple[str, ...] = (
    "PERSON_NAME",
    "PERSON",
    "NAME",
    "FIRST_NAME",
    "LAST_NAME",
    "FULL_NAME",
    "ADDRESS",
    "LOCATION",
    "CITY",
    "EMAIL",
    "PHONE",
    "PHONE_NUMBER",
    "DATE",
    "TIME",
    "ORGANIZATION",
    "ORG",
    "COMPANY",
    "CREDIT_CARD",
    "SSN",
    "IP_ADDRESS",
    "URL",
    "REDACTED",
    "PII",
    "MASK",
    "MASKED",
)

# Регэксп 1: заранее известные «осмысленные» токены (в т.ч. с суффиксом _N).
# Пример совпадений: [PERSON_NAME], [ADDRESS], [[EMAIL_1]], [PHONE_002].
_KNOWN_TOKEN_PATTERN: Pattern[str] = re.compile(
    r"\[{1,2}(?:" + "|".join(_KNOWN_PLACEHOLDER_STEMS) + r")(?:_\d+)?\]{1,2}",
    re.ASCII,
)

# Регэксп 2: общий шаблон служебного токена вида [[WORD_1]] / [WORD].
# Ловит незнакомые, но структурно похожие токены (ALL-CAPS + опц. суффикс),
# требуя минимум 2 символа основы, чтобы не цеплять одиночные буквы.
# ASCII-флаг гарантирует, что кириллица (например «[ДА]») НЕ попадёт.
_GENERIC_TOKEN_PATTERN: Pattern[str] = re.compile(
    r"\[{1,2}[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*\]{1,2}",
    re.ASCII,
)


def find_placeholder_leaks(text: str) -> List[str]:
    """Возвращает отсортированный список уникальных найденных плейсхолдеров.

    Args:
        text: финальный текст, предназначенный пользователю.

    Returns:
        Список уникальных токенов-заглушек, найденных в тексте. Пустой
        список означает, что протечки не обнаружено.

    Notes:
        Функция чистая (без побочных эффектов) и не логирует содержимое,
        чтобы не писать потенциальные персональные данные в логи.
    """
    if not text:
        return []

    found: set[str] = set()
    for pattern in (_KNOWN_TOKEN_PATTERN, _GENERIC_TOKEN_PATTERN):
        found.update(match.group(0) for match in pattern.finditer(text))
    return sorted(found)


def has_placeholder_leak(text: str) -> bool:
    """Быстрая проверка: есть ли в тексте хотя бы один служебный плейсхолдер.

    Args:
        text: финальный текст, предназначенный пользователю.

    Returns:
        ``True``, если найден хотя бы один токен-заглушка, иначе ``False``.
    """
    if not text:
        return False
    return bool(
        _KNOWN_TOKEN_PATTERN.search(text)
        or _GENERIC_TOKEN_PATTERN.search(text)
    )


# ---------------------------------------------------------------------------
# Усиление промпта для повторной попытки
# ---------------------------------------------------------------------------
PLACEHOLDER_GUARD_INSTRUCTION: str = (
    "\n\nКРИТИЧЕСКОЕ ТРЕБОВАНИЕ К ВЫВОДУ:\n"
    "Категорически запрещено заменять реальные слова служебными "
    "плейсхолдерами или заглушками в квадратных скобках "
    "(например [PERSON_NAME], [ADDRESS], [NAME], [EMAIL], [PHONE], "
    "[[PERSON_1]] и любыми похожими токенами из заглавных латинских букв "
    "в скобках). Не обезличивай текст и не маскируй имена, адреса, "
    "контакты. Сохрани реальные слова исходного текста как есть. Если в "
    "тексте есть имя или адрес — перенеси его в отредактированный текст "
    "без изменений, не превращая в токен."
)


def harden_prompt_against_placeholders(prompt: str) -> str:
    """Добавляет к промпту явный запрет на генерацию плейсхолдеров.

    Используется при повторной попытке (retry) после того, как в ответе
    LLM были обнаружены служебные токены.

    Args:
        prompt: исходный промпт.

    Returns:
        Промпт с добавленной анти-плейсхолдерной инструкцией. Повторное
        применение не дублирует инструкцию.
    """
    if PLACEHOLDER_GUARD_INSTRUCTION.strip() in prompt:
        return prompt
    return prompt + PLACEHOLDER_GUARD_INSTRUCTION
